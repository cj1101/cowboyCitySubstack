export function PinMark({ category, title, size = 28 }: { category: PinCategory; title?: string; size?: number }) {
  const art = ART[category];
  const pixels = art.rows.flatMap((row, y) =>
    [...row].flatMap((cell, x) => {
      const fill = cell === "#" ? art.fill : cell === "+" ? art.accent : cell === "@" ? INK : "";
      if (!fill) return [];
      return [<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={fill} />];
    })
  );
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
      className="pixel-image pointer-events-none shrink-0"
    >
      {title ? <title>{title}</title> : null}
      {pixels}
    </svg>
  );
}
